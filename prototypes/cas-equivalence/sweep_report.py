"""PROTOTYPE (#40): turn results-hard.json into RESULTS-hard.md (facts; the hand-written recommendation is analysis-hard.md, appended)."""
import json, os, statistics
from collections import defaultdict
from strategies import STRATEGIES

SIDS = [s[0] for s in STRATEGIES]
NAMES = {s[0]: s[1] for s in STRATEGIES}

def q(vals, p):
    v = sorted(vals)
    return v[min(len(v) - 1, int(round(p * (len(v) - 1))))] if v else float("nan")

def f0(x): return "-" if x is None or x != x else f"{x:.0f}"

def agg(rows):
    """rows of one kind -> {(key,sid,budget): cell} using the median-wall repetition."""
    g = defaultdict(list)
    for r in rows: g[(r["key"], r["sid"], r["budget"])].append(r)
    out = {}
    for k, rs in g.items():
        rs = sorted(rs, key=lambda r: r["wall_ms"])
        m = rs[len(rs) // 2]
        out[k] = dict(m, wall_ms=statistics.median(r["wall_ms"] for r in rs),
                      inner_ms=statistics.median([r["inner_ms"] for r in rs if r["inner_ms"] is not None] or [float("nan")]),
                      n_to=sum(r["status"] == "timeout" for r in rs), n=len(rs), verdicts=sorted({r["verdict"] for r in rs}))
    return out

def write(src, dst):
    D = json.load(open(src)); M = D["meta"]
    steps = {s["key"]: s for s in D["steps"]}
    orig = [k for k in steps if steps[k]["set"] == "orig"]; hard = [k for k in steps if steps[k]["set"] == "hard"]
    strat = agg([r for r in D["rows"] if r["kind"] == "strategy"]); stk = agg([r for r in D["rows"] if r["kind"] == "stack"])
    budgets = M["budgets"]; big = max(budgets)
    L = []
    L.append("# RESULTS-hard: harder step set and the interactive timeout budget (#40)\n")
    L.append("PROTOTYPE output, generated by `sweep.py report` from `results-hard.json` (raw rows: every call, every repetition). "
             "Facts first (sections 1-9); the Recommendation is a separate, clearly labelled section at the end (section 10, from `analysis-hard.md`).\n")
    fa, fl, wp = M["floor_alone_ms"], M["floor_under_load_ms"], M["warm_pool_s0e_roundtrip_ms"]
    L.append(f"Machine: {M['machine']} (WSL2 on a shared 32-core machine; other agents were running, so absolute numbers are indicative, ratios matter). "
             f"Run {M['date']}. Each (step, strategy, budget) cell was run {M['reps']} times; cell time = median of the repetitions, cell outcome = the repetition with the median time. "
             f"Every call is a forked child killed on timeout (`run.py` mechanism). At most {M['workers']} calls ran in parallel (sweep processes; each runs one child at a time). Sweep wall time {M['sweep_seconds']:.0f} s.\n")
    L.append("**Fork/IPC floor (a no-op through the same fork-and-pipe mechanism), reported separately so it is not read as CAS time:**\n")
    L.append("| measurement | median ms | p95 ms | max ms | n |\n|---|---|---|---|---|")
    L.append(f"| no-op fork+pipe, run alone before the sweep | {fa['median']:.1f} | {fa['p95']:.1f} | {fa['max']:.1f} | {fa['n']} |")
    L.append(f"| no-op fork+pipe, measured inside the parallel sweep workers (4 at once) | {fl['median']:.1f} | {fl['p95']:.1f} | {fl['max']:.1f} | {fl['n']} |")
    L.append(f"| warm long-lived worker: round trip of S0e (a trivial strategy) incl. pickling the parsed step | {wp['median']:.2f} | {wp['p95']:.2f} | {wp['max']:.2f} | {wp['n']} |")
    L.append("\nColumns below: `wall` = parent-side time from fork to verdict (includes the floor); `CAS` = the child's own timer around the strategy call (excludes fork and IPC; only available for calls that finished). "
             "Net-of-floor wall time is roughly wall minus the floor median.\n")
    # ---- 1 step set
    L.append("## 1. The hard step set (hand-labelled)\n")
    L.append("Same label vocabulary as `steps.py`: EQUIV, NOT_EQUIV, DOMAIN (equal only under a restriction), ONEWAY (after follows from before, not conversely). Kinds: expr, eq, ineq (relational), sys (system in `cases`). The original 20 steps are unchanged in `steps.py`; their keys here are O1..O20. Labels and reasons are mine.\n")
    L.append("| key | cat | before | after | kind | expected | parse | parse ms (warm) | reason |\n|---|---|---|---|---|---|---|---|---|")
    for k in hard:
        s = steps[k]; pi = D["parse"][k]
        pr = "ok" if pi["status"] == "ok" else f"REJECT/{pi['status']}: {pi['detail'][:60]}"
        L.append(f"| {k} | {s['cat']} | `{s['before']}` | `{s['after']}` | {s['kind']} | {s['expected']} | {pr} | {f0(pi.get('warm_ms'))} | {s['why'].replace('|', '/')} |")
    rej = [k for k in hard if D["parse"][k]["status"] != "ok"]
    pw = [D["parse"][k]["warm_ms"] for k in hard if D["parse"][k]["status"] == "ok" and D["parse"][k]["warm_ms"]]
    po = [D["parse"][k]["warm_ms"] for k in orig if D["parse"][k]["status"] == "ok" and D["parse"][k]["warm_ms"]]
    L.append(f"\nParse stack (ANTLR strict + normalizer + whitelist + Lark cross-check, before AND after, plus the unevaluated parse; in-process, warm): "
             f"hard set {len(hard) - len(rej)}/{len(hard)} accepted, rejected or timed out: {', '.join(rej)}. "
             f"Warm parse time of a step (4 parses): hard set median {f0(statistics.median(pw))} ms, p95 {f0(q(pw, .95))}, max {f0(max(pw))}; original 20: median {f0(statistics.median(po))} ms, p95 {f0(q(po, .95))}, max {f0(max(po))}. Parse time is part of the per-step cost and is not capped by the budget in the strategy tables (it runs before them); the stack tables in section 7 include it.\n")
    # ---- 2 per strategy tables
    for setname, ks, title in (("hard", hard, "hard set"), ("orig", orig, "original 20 steps (for comparison)")):
        ks = [k for k in ks if D["parse"][k]["status"] == "ok"]
        L.append(f"## {'2' if setname == 'hard' else '3'}. Per strategy and budget, {title} ({len(ks)} parsed steps)\n")
        L.append("Scoring as in `run.py`: correct = verdict matches the label (EQUIV needs EQ; NOT_EQUIV any non-equal verdict; DOMAIN needs EQ_DOM/NARROW/WIDER, plain NEQ is partial; ONEWAY needs WIDER, NEQ/NARROW partial). UND = undecided, TO = killed at the budget, NA = not applicable. Wall/CAS in ms over the non-NA cells.\n")
        for b in budgets:
            L.append(f"### budget {b*1000:.0f} ms\n")
            L.append("| strategy | correct | partial | wrong | UND | TO | ERR | NA | wall median | wall p95 | wall max | CAS median | CAS max |\n|---|---|---|---|---|---|---|---|---|---|---|---|---|")
            for sid in SIDS:
                cs = [strat[(k, sid, b)] for k in ks if (k, sid, b) in strat]
                n = lambda sc: sum(c["score"] == sc and c["verdict"] not in ("UND", "TO", "ERR") for c in cs)
                nn = [c for c in cs if c["verdict"] != "NA"]
                w = [c["wall_ms"] for c in nn]; ci = [c["inner_ms"] for c in nn if c["inner_ms"] == c["inner_ms"]]
                L.append(f"| {sid} | {n('ok')} | {n('partial')} | {n('wrong')} | {sum(c['verdict']=='UND' for c in cs)} | {sum(c['verdict']=='TO' for c in cs)} | {sum(c['verdict']=='ERR' for c in cs)} | {sum(c['verdict']=='NA' for c in cs)} | "
                         f"{f0(statistics.median(w) if w else None)} | {f0(q(w, .95))} | {f0(max(w) if w else None)} | {f0(statistics.median(ci) if ci else None)} | {f0(max(ci) if ci else None)} |")
            L.append("")
    # ---- 4 verdict matrix
    L.append("## 4. Hard set: verdict and time per step and strategy at the largest budget\n")
    L.append(f"Budget {big*1000:.0f} ms. Cell = verdict, wall ms; `!` wrong, `~` partial, `TO` killed. Systems: only S0 and S5 exist (NA elsewhere, left blank); inequalities use the sign-aware wrapper (`hardlib.py`).\n")
    ids = [s for s in SIDS]
    L.append("| key | expected | " + " | ".join(ids) + " |\n|---|---|" + "---|" * len(ids))
    for k in hard:
        if D["parse"][k]["status"] != "ok":
            L.append(f"| {k} | {steps[k]['expected']} | parse {D['parse'][k]['status']} |" + " |" * (len(ids) - 1)); continue
        cells = []
        for sid in ids:
            c = strat.get((k, sid, big))
            if not c or c["verdict"] == "NA": cells.append(""); continue
            mark = {"wrong": " !", "partial": " ~"}.get(c["score"], "") if c["verdict"] not in ("UND", "TO", "ERR") else ""
            cells.append(f"{c['verdict']}{mark} {c['wall_ms']:.0f}")
        L.append(f"| {k} | {steps[k]['expected']} | " + " | ".join(cells) + " |")
    L.append("")
    # ---- 5 blowups
    L.append("## 5. Which steps blow up in which strategy\n")
    L.append("Cells (hard + original) whose wall time exceeded 100 ms in the median at any budget, or that timed out at any budget. Columns: median wall ms at each budget (`TO` = timed out in at least 2 of the repetitions); `true time` = one run of the same call with a 10 s budget (only for calls that timed out at the largest budget); `CAS` = child timer at the largest budget.\n")
    ref = {(r["key"], r["sid"]): r for r in D["ref"] if r["kind"] == "strategy"}
    L.append("| key | strategy | " + " | ".join(f"{b*1000:.0f} ms" for b in budgets) + " | true time (10 s budget) | verdict at largest budget |\n|---|---|" + "---|" * (len(budgets) + 2))
    cnt = 0
    for k in steps:
        if D["parse"][k]["status"] != "ok": continue
        for sid in SIDS:
            cs = [strat.get((k, sid, b)) for b in budgets]
            if any(c and (c["wall_ms"] > 100 or c["n_to"] > 0) for c in cs if c) and not all(c["verdict"] == "NA" for c in cs if c):
                cnt += 1
                r = ref.get((k, sid))
                tt = "-" if r is None else ("still TO" if r["status"] == "timeout" else f"{r['wall_ms']:.0f} ms ({r['verdict']})")
                L.append(f"| {k} | {sid} | " + " | ".join(("TO" if c["n_to"] * 2 > c["n"] else f"{c['wall_ms']:.0f}") if c else "-" for c in cs) + f" | {tt} | {strat[(k, sid, big)]['verdict']} |")
    if not cnt: L.append("| (none) | | " + " | " * len(budgets))
    L.append("")
    # timeouts per strategy over budgets
    L.append("Timeouts per strategy (hard set + original 20, parsed steps) at each budget:\n")
    L.append("| strategy | " + " | ".join(f"{b*1000:.0f} ms" for b in budgets) + " |\n|---|" + "---|" * len(budgets))
    pk = [k for k in steps if D["parse"][k]["status"] == "ok"]
    for sid in SIDS:
        L.append(f"| {sid} | " + " | ".join(str(sum(strat[(k, sid, b)]["verdict"] == "TO" for k in pk if (k, sid, b) in strat)) for b in budgets) + " |")
    L.append("")
    # wrong verdicts
    L.append("## 6. Wrong or partial verdicts on the hard set (largest budget)\n")
    L.append("| key | expected | strategy | verdict | detail |\n|---|---|---|---|---|")
    for k in hard:
        for sid in SIDS:
            c = strat.get((k, sid, big))
            if c and c["score"] in ("wrong",) and c["verdict"] not in ("UND", "TO", "ERR", "NA"):
                L.append(f"| {k} | {steps[k]['expected']} | {sid} | {c['verdict']} | {str(c['detail'])[:110].replace('|','/')} |")
    L.append("")
    # ---- 7 full stack
    L.append("## 7. The recommended stack end to end (RESULTS.md section 4.3)\n")
    L.append("One forked worker per step runs: guarded parse (4 parses) -> equation/inequality/system lines: S5r first (decisive on NARROW/WIDER/NEQ) -> S3r numeric reject -> S4 layered cheap zero-checks (ends in simplify) -> on a proven EQ, S7 domain flag (EQ_DOM = amber; EQ_NODOM = proven equal but S7 only handles one variable, so the domain is unchecked = amber). "
             "Systems: S5 only. Whole stack under ONE deadline (the budget), killed at the budget; a kill or a Reject is UND (amber 'cannot check'). Scored against the labels like a strategy (DOMAIN needs EQ_DOM/NARROW/WIDER, ONEWAY needs WIDER).\n")
    L.append("| set | budget | correct | partial | wrong | UND (incl. TO, parse rejects, EQ_NODOM) | of which EQ_NODOM | of which TO | wall median ms | p95 | max |\n|---|---|---|---|---|---|---|---|---|---|---|")
    for setname, ks in (("hard", hard), ("original 20", orig)):
        for b in budgets:
            cs = [stk[(k, "stack", b)] for k in ks if (k, "stack", b) in stk]
            ok = sum(c["score"] == "ok" and c["verdict"] not in ("TO", "ERR", "UND", "EQ_NODOM") for c in cs)
            pa = sum(c["score"] == "partial" for c in cs); wr = sum(c["score"] == "wrong" for c in cs)
            und = sum(c["verdict"] in ("UND", "TO", "ERR", "EQ_NODOM") for c in cs); nd = sum(c["verdict"] == "EQ_NODOM" for c in cs); to = sum(c["verdict"] == "TO" for c in cs)
            w = [c["wall_ms"] for c in cs]
            L.append(f"| {setname} ({len(ks)} steps, {len(cs)} parsed) | {b*1000:.0f} ms | {ok} | {pa} | {wr} | {und + len(ks) - len(cs)} | {nd} | {to} | {f0(statistics.median(w))} | {f0(q(w, .95))} | {f0(max(w))} |")
    L.append("\n(Parse rejects have no stack row; they are counted as UND in the 'UND' column.)\n")
    L.append("Per-step stack result at each budget, hard set (verdict, wall ms; TO = killed). Scores in brackets: ok / part / wrong / und.\n")
    L.append("| key | expected | " + " | ".join(f"{b*1000:.0f} ms" for b in budgets) + " | uncapped stage times (ms, 10 s budget, median of reps) |\n|---|---|" + "---|" * (len(budgets) + 1))
    tr = defaultdict(list)
    for r in D["trace"]: tr[r["key"]].append(r)
    for k in hard:
        if D["parse"][k]["status"] != "ok":
            L.append(f"| {k} | {steps[k]['expected']} | parse {D['parse'][k]['status']} |" + " |" * len(budgets)); continue
        cells = []
        for b in budgets:
            c = stk[(k, "stack", b)]
            cells.append(f"{c['verdict']} ({c['score'][:4]}) {c['wall_ms']:.0f}")
        stages = defaultdict(list)
        for r in tr[k]:
            for n_, m_, v_ in r["trace"]: stages[n_].append(m_)
        st = ", ".join(f"{n_} {statistics.median(v_):.0f}" for n_, v_ in stages.items())
        L.append(f"| {k} | {steps[k]['expected']} | " + " | ".join(cells) + f" | {st} |")
    # per stage
    L.append("\nPer-stage cost over all parsed steps, uncapped (10 s budget, median of repetitions per step), ms:\n")
    L.append("| stage | steps that reached it | median | p95 | max | steps over 100 ms | over 500 ms |\n|---|---|---|---|---|---|---|")
    perstage = defaultdict(dict)
    for k, rs in tr.items():
        stages = defaultdict(list)
        for r in rs:
            for n_, m_, v_ in r["trace"]: stages[n_].append(m_)
        for n_, v_ in stages.items(): perstage[n_][k] = statistics.median(v_)
    for n_ in ("parse", "S5r", "S3r", "S4", "S7"):
        v = list(perstage[n_].values())
        if v: L.append(f"| {n_} | {len(v)} | {f0(statistics.median(v))} | {f0(q(v, .95))} | {f0(max(v))} | {sum(x > 100 for x in v)} | {sum(x > 500 for x in v)} |")
    tw = [(statistics.median(r["wall_ms"] for r in rs), k) for k, rs in tr.items()]
    tw.sort()
    L.append("\nUncapped whole-stack wall time (10 s budget, includes fork): median %s ms, p95 %s, max %s; steps that did not finish in 10 s: %s.\n" % (
        f0(statistics.median(t for t, _ in tw)), f0(q([t for t, _ in tw], .95)), f0(tw[-1][0]), ", ".join(sorted({r["key"] for rs in tr.values() for r in rs if r["status"] == "timeout"})) or "none"))
    # CAS-only (no parse) cost of the stack, and parse breakdown
    L.append("\nStack cost split into parse and CAS stages (uncapped 10 s run, per step median of reps; CAS = S5r+S3r+S4+S7, no parse, no fork):\n")
    L.append("| set | part | median ms | p95 | max |\n|---|---|---|---|---|")
    for setname, ks in (("hard", hard), ("original 20", orig)):
        cas, par = [], []
        for k in ks:
            if k not in tr: continue
            per = []
            for r in tr[k]:
                per.append((sum(m for n_, m, v_ in r["trace"] if n_ != "parse"), sum(m for n_, m, v_ in r["trace"] if n_ == "parse")))
            cas.append(statistics.median(x for x, _ in per)); par.append(statistics.median(y for _, y in per))
        L.append(f"| {setname} | parse (4 parses, in the child) | {f0(statistics.median(par))} | {f0(q(par, .95))} | {f0(max(par))} |")
        L.append(f"| {setname} | CAS stages only | {f0(statistics.median(cas))} | {f0(q(cas, .95))} | {f0(max(cas))} |")
    bd = {k: D["parse"][k]["breakdown_ms"] for k in steps if D["parse"][k].get("breakdown_ms")}
    if bd:
        L.append("\nWhere the parse time goes (warm, in-process, before+after pieces of one step, min of 2 runs), ms. `same` is the evaluated-vs-Lark comparison (`parsing.same`: simplify on a mismatch):\n")
        L.append("| set | part | median | p95 | max |\n|---|---|---|---|---|")
        for setname, ks in (("hard", hard), ("original 20", orig)):
            for part in ("antlr", "lark", "same"):
                v = [bd[k][part] for k in ks if k in bd]
                if v: L.append(f"| {setname} | {part} | {f0(statistics.median(v))} | {f0(q(v, .95))} | {f0(max(v))} |")
        top = sorted(bd.items(), key=lambda kv: -sum(kv[1].values()))[:5]
        L.append("\nSlowest parses: " + "; ".join(f"{k} (antlr {v['antlr']:.0f}, lark {v['lark']:.0f}, same {v['same']:.0f})" for k, v in top) + ".\n")
    # ---- 8 pool
    L.append("## 8. Warm worker vs fork-per-check (datapoint)\n")
    pb = M["pool_budget"]
    pool = agg(D["pool"])
    pk_ = [k for k in steps if D["parse"][k]["status"] == "ok"]
    both = [(k, sid) for k in pk_ for sid in SIDS if (k, sid, pb) in strat and (k, sid, pb) in pool]
    wf = [strat[(k, s, pb)]["wall_ms"] for k, s in both if strat[(k, s, pb)]["verdict"] not in ("TO",) and pool[(k, s, pb)]["verdict"] not in ("TO",)]
    wp_ = [pool[(k, s, pb)]["wall_ms"] for k, s in both if strat[(k, s, pb)]["verdict"] not in ("TO",) and pool[(k, s, pb)]["verdict"] not in ("TO",)]
    L.append(f"One long-lived forked worker (strategy loaded, killed and re-forked after a timeout; the re-fork is not counted in the timed call), all strategy calls sequentially, budget {pb*1000:.0f} ms, {M['reps']} reps, run alone (not in parallel). "
             f"The parsed step is pickled to the worker for each call (that is included). Timeouts: fork-per-check {sum(strat[(k,s,pb)]['verdict']=='TO' for k,s in both)}, warm worker {sum(pool[(k,s,pb)]['verdict']=='TO' for k,s in both)} of {len(both)} cells; worker re-forks after a kill: {M['pool_respawns']} (over all reps).\n")
    L.append("| over the cells that finished in both | median ms | p95 | max |\n|---|---|---|---|")
    L.append(f"| fork per check (wall) | {f0(statistics.median(wf))} | {f0(q(wf, .95))} | {f0(max(wf))} |\n| warm worker (wall) | {f0(statistics.median(wp_))} | {f0(q(wp_, .95))} | {f0(max(wp_))} |")
    diff = [a - b for a, b in zip(wf, wp_)]
    L.append(f"\nMedian saving per call: {statistics.median(diff):.1f} ms (about the fork floor); p95 saving {q(diff, .95):.1f} ms. Warm worker verdicts that differ from fork-per-check on finished cells: "
             f"{sum(strat[(k,s,pb)]['verdict'] != pool[(k,s,pb)]['verdict'] for k, s in both if strat[(k,s,pb)]['verdict'] != 'TO' and pool[(k,s,pb)]['verdict'] != 'TO')}.\n")
    open(dst, "w").write("\n".join(L) + "\n")
    ap = os.path.join(os.path.dirname(os.path.abspath(dst)), "analysis-hard.md")
    if os.path.exists(ap): open(dst, "a").write("\n" + open(ap).read())
    print("wrote", dst)
